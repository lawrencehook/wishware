"""Engrave sheet music for movements imported from Humdrum (.krn) scores, with Verovio.

    python music/tools/typeset.py --work <cache dir> [folder ...]

For each movement in imports.json whose source is a .krn file, and which has no sheet music cut
from a printed edition by engrave.py, this writes notation/<folder>/<m>-<page>.webp and
notation/<folder>/<m>.js in the form engrave.py writes. Each measure heard is matched to the
engraved measure that starts at the same point of the score played once through; a movement
where they do not line up is skipped and reported.

Needs: Python with verovio, and rsvg-convert, magick and cwebp on the path.
"""
import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import verovio

HERE = Path(__file__).resolve().parent
MUSIC = HERE.parent
sys.path.insert(0, str(HERE))
from midi import fetch  # noqa: E402

WIDTH = 1240  # pixels, as engrave.py's pages
MARK = '// Generated by music/tools/typeset.py'
SVG = '{http://www.w3.org/2000/svg}'


def lines(node):
    """[(x1, x2, y)] of the staff lines under a node."""
    found = []
    for staff in node.iter(SVG + 'g'):
        if 'staff' in (staff.get('class') or '').split():
            for path in staff.findall(SVG + 'path'):
                numbers = [float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', path.get('d'))]
                if len(numbers) == 4 and numbers[1] == numbers[3]:
                    found.append((numbers[0], numbers[2], numbers[1]))
    return found


def layout(svg):
    """Page height in pixels, and per system (top, bottom, [(x, width, id)] of its measures), in pixels."""
    root = ET.fromstring(svg)
    inner = next(node for node in root.iter(SVG + 'svg') if node.get('class') == 'definition-scale')
    view = [float(n) for n in inner.get('viewBox').split()]
    scale = WIDTH / view[2]
    margin = next(node for node in inner.iter(SVG + 'g') if node.get('class') == 'page-margin')
    dx, dy = (float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', margin.get('transform')))
    systems = []
    for system in margin.iter(SVG + 'g'):
        if 'system' not in (system.get('class') or '').split():
            continue
        measures = []
        for measure in system.iter(SVG + 'g'):
            if 'measure' in (measure.get('class') or '').split():
                inside = lines(measure)
                left, right = min(line[0] for line in inside), max(line[1] for line in inside)
                measures.append(((left + dx) * scale, (right - left) * scale, measure.get('id')))
        ys = [line[2] for line in lines(system)]
        systems.append(((min(ys) + dy) * scale, (max(ys) + dy) * scale, measures))
    return round(view[3] * scale), systems


def typeset(folder, index, url, work, notation):
    toolkit = verovio.toolkit()
    toolkit.setOptions({'pageWidth': 2100, 'pageHeight': 2970, 'scale': 100, 'header': 'none', 'footer': 'none',
                        'pageMarginTop': 60, 'pageMarginBottom': 60, 'pageMarginLeft': 70, 'pageMarginRight': 70,
                        'spacingSystem': 14, 'justifyVertically': False})
    if not toolkit.loadData(fetch(url, work).decode('utf-8', 'replace')):
        return 'Verovio could not read the score'
    pages = []
    for page in range(1, toolkit.getPageCount() + 1):
        svg = toolkit.renderToSVG(page)
        pages.append((svg, *layout(svg)))
    # Where each engraved measure starts, in quarter notes of the score played once through.
    begins = {event['measureOn']: event['qstamp'] for event in toolkit.renderToTimemap({'includeMeasures': True}) if 'measureOn' in event}
    printed = [begins[name] for _, _, systems in pages for _, _, measures in systems for _, _, name in measures]
    # The same for each measure of the notes: a measure lasts until the next one heard.
    heard = notation['bars']
    linear = notation.get('linear') or list(range(len(heard)))
    lengths = {}
    for i, (bar, after) in enumerate(zip(heard, heard[1:])):
        lengths.setdefault(linear[i], after[0] - bar[0])
    starts, now = {}, 0
    for number in range(max(linear) + 1):
        starts[number] = now
        now += lengths.get(number, 0)
    missing = [number for number in set(linear) if number not in lengths and number != linear[-1]]
    astray = [number for number, start in starts.items() if min(abs(start - begin) for begin in printed) > 0.02]
    # A last measure that only holds the end of the final notes is shown on the last one engraved.
    astray = [number for number in astray if number < len(starts) - 2 or starts[number] < printed[-1]]
    if missing or astray:
        return '%d of %d measures do not start where an engraved measure does' % (len(missing) + len(astray), len(starts))
    place = lambda start: max(i for i, begin in enumerate(printed) if begin <= start + 0.02)

    out = MUSIC / 'notation' / folder
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob('%d-*.webp' % index):
        old.unlink()
    systems, bars = [], []
    for number, (svg, height, found) in enumerate(pages, 1):
        # Crop each page to its music, and split the space between systems evenly.
        top = max(0, round(found[0][0] - 70))
        bottom = min(height, round(found[-1][1] + 70))
        edges = [top] + [round((a[1] + b[0]) / 2) for a, b in zip(found, found[1:])] + [bottom]
        file = '%s/%d-%d.webp' % (folder, index, number)
        source, png = work / 'typeset.svg', work / 'typeset.png'
        source.write_text(svg, encoding='utf-8')
        subprocess.run(['rsvg-convert', '-w', str(WIDTH), '-b', 'white', str(source), '-o', str(png)], check=True)
        subprocess.run(['magick', str(png), '-crop', '%dx%d+0+%d' % (WIDTH, bottom - top, top), '+repage',
                        '-colorspace', 'Gray', '-posterize', '6', str(png)], check=True)
        subprocess.run(['cwebp', '-quiet', '-lossless', str(png), '-o', str(MUSIC / 'notation' / file)], check=True)
        for (_, _, measures), y, below in zip(found, edges, edges[1:]):
            for x, width, _ in measures:
                bars.append([len(systems), round(x), round(width)])
            systems.append({'file': file, 'imageHeight': bottom - top, 'y': y - top, 'h': below - y})
    play = [[bar[0], place(starts[linear[i]])] for i, bar in enumerate(heard)]
    data = {'width': WIDTH, 'pdf': re.sub(r'raw\.githubusercontent\.com/([^/]+/[^/]+)/', r'github.com/\1/blob/', url),
            'pickup': notation['bars'][0][1] == 0, 'full': True, 'systems': systems, 'bars': bars, 'play': play}
    (out / ('%d.js' % index)).write_text(
        MARK + ' from the encoded score at `pdf`. Do not edit.\n'
        'const ENGRAVING = ' + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
    return None


def notations(folder):
    script = ('const fs=require("fs");const d=process.argv[1]+"/";'
              'const score=new Function(fs.readFileSync(d+"notes.js","utf8")+";"+fs.readFileSync(d+"measures.js","utf8")+";return score")();'
              'console.log(JSON.stringify(score.movements.map(m=>m.notation)))')
    return json.loads(subprocess.run(['node', '-e', script, str(MUSIC / 'pieces' / folder)], capture_output=True, text=True, check=True).stdout)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--work', required=True, type=Path)
    parser.add_argument('folders', nargs='*')
    args = parser.parse_args()
    args.work.mkdir(parents=True, exist_ok=True)
    imports = json.loads((HERE / 'imports.json').read_text(encoding='utf-8'))
    done = skipped = 0
    for folder in args.folders or imports:
        entries = imports[folder]
        if not any(entry['midi'].endswith('.krn') for entry in entries):
            continue
        found = notations(folder)
        for index, entry in enumerate(entries):
            target = MUSIC / 'notation' / folder / ('%d.js' % index)
            if not entry['midi'].endswith('.krn') or (target.exists() and not target.read_text(encoding='utf-8').startswith(MARK)):
                continue
            problem = typeset(folder, index, entry['midi'], args.work, found[index])
            if problem:
                skipped += 1
                print('skip  %s %d (%s): %s' % (folder, index, entry['name'], problem))
            else:
                done += 1
    print('%d movements engraved, %d skipped' % (done, skipped))


if __name__ == '__main__':
    main()
